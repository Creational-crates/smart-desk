const GERBER_SCALE = 10000;

const sanitizeFilePart = (value) => String(value || "pcb-project")
    .replace(/[<>:"/\\|?*\u0000-\u001f]/g, "-")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 64) || "pcb-project";

const formatNumber = (value, places = 4) => Number(value).toFixed(places);
const gerberCoordinate = (value) => {
    const scaled = Math.round(Number(value) * GERBER_SCALE);
    return `${scaled < 0 ? "-" : ""}${String(Math.abs(scaled)).padStart(7, "0")}`;
};
const gerberPoint = (point) => `X${gerberCoordinate(point.x)}Y${gerberCoordinate(point.y)}`;

function csvCell(value) {
    const text = String(value ?? "");
    return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

function pointInPolygon(point, polygon) {
    let inside = false;
    for (let index = 0, previous = polygon.length - 1; index < polygon.length; previous = index, index += 1) {
        const a = polygon[index];
        const b = polygon[previous];
        if ((a.y > point.y) !== (b.y > point.y) &&
            point.x < ((b.x - a.x) * (point.y - a.y)) / (b.y - a.y || Number.EPSILON) + a.x) inside = !inside;
    }
    return inside;
}

function csvRows(rows) {
    return `${rows.map((row) => row.map(csvCell).join(",")).join("\r\n")}\r\n`;
}

function boundsOf(points) {
    return points.reduce((bounds, point) => ({
        minX: Math.min(bounds.minX, point.x),
        maxX: Math.max(bounds.maxX, point.x),
        minY: Math.min(bounds.minY, point.y),
        maxY: Math.max(bounds.maxY, point.y)
    }), { minX: Infinity, maxX: -Infinity, minY: Infinity, maxY: -Infinity });
}

function orientation(a, b, c) {
    return (b.x - a.x) * (c.y - a.y) - (b.y - a.y) * (c.x - a.x);
}

function segmentsIntersect(a, b, c, d) {
    const abC = orientation(a, b, c);
    const abD = orientation(a, b, d);
    const cdA = orientation(c, d, a);
    const cdB = orientation(c, d, b);
    const onSegment = (first, point, last) =>
        point.x >= Math.min(first.x, last.x) - 1e-8 && point.x <= Math.max(first.x, last.x) + 1e-8 &&
        point.y >= Math.min(first.y, last.y) - 1e-8 && point.y <= Math.max(first.y, last.y) + 1e-8;
    return (((abC > 0 && abD < 0) || (abC < 0 && abD > 0)) &&
        ((cdA > 0 && cdB < 0) || (cdA < 0 && cdB > 0))) ||
        (Math.abs(abC) < 1e-8 && onSegment(a, c, b)) ||
        (Math.abs(abD) < 1e-8 && onSegment(a, d, b)) ||
        (Math.abs(cdA) < 1e-8 && onSegment(c, a, d)) ||
        (Math.abs(cdB) < 1e-8 && onSegment(c, b, d));
}

function polygonArea(points) {
    return Math.abs(points.reduce((sum, point, index) => {
        const next = points[(index + 1) % points.length];
        return sum + point.x * next.y - next.x * point.y;
    }, 0) / 2);
}

function validateOutline(outline) {
    if (!Array.isArray(outline) || outline.length < 3 || outline.length > 100 ||
        outline.some((point) => !Number.isFinite(point?.x) || !Number.isFinite(point?.y))) {
        return "The board outline needs at least three finite coordinate points.";
    }
    for (let first = 0; first < outline.length; first += 1) {
        const firstNext = (first + 1) % outline.length;
        for (let second = first + 1; second < outline.length; second += 1) {
            const secondNext = (second + 1) % outline.length;
            if (first === second || firstNext === second || secondNext === first) continue;
            if (segmentsIntersect(outline[first], outline[firstNext], outline[second], outline[secondNext])) {
                return "The board outline crosses itself; a clean closed profile is required.";
            }
        }
    }
    if (polygonArea(outline) <= 0.001) return "The board outline has no usable area.";
    return null;
}

function rotatePoint(point, footprint) {
    const radians = (footprint.rotation || 0) * Math.PI / 180;
    return {
        x: footprint.x + point.x * Math.cos(radians) - point.y * Math.sin(radians),
        y: footprint.y + point.x * Math.sin(radians) + point.y * Math.cos(radians)
    };
}

function createGerberHeader(title) {
    const safeTitle = String(title).replace(/[^\x20-\x7e]/g, " ").replace(/[\r\n*]/g, " ");
    return [
        `G04 ${safeTitle} - generated by Aqua PCB Studio*`,
        "%FSLAX34Y34*%",
        "%MOMM*%",
        "%LPD*%"
    ];
}

function createGerberCopper(project, layer, options, getPartDefinition) {
    const layout = project.layout;
    const content = createGerberHeader(`${project.name} · ${layer.name}`);
    const apertures = new Map();
    const emittedApertures = new Set();
    const addAperture = (shape, first, second = null) => {
        const key = `${shape}:${first}:${second ?? ""}`;
        if (!apertures.has(key)) apertures.set(key, 10 + apertures.size);
        const code = apertures.get(key);
        if (!emittedApertures.has(code)) {
            const dimensions = shape === "C" ? first : `${first}X${second}`;
            content.push(`%ADD${code}${shape},${dimensions}*%`);
            emittedApertures.add(code);
        }
        return code;
    };
    layout.tracks.filter((track) => track.layerId === layer.id).forEach((track) => {
        const code = addAperture("C", formatNumber(track.width));
        content.push(`D${code}*`);
        track.points.forEach((point, index) => {
            content.push(`${gerberPoint(point)}D${index ? "01" : "02"}*`);
        });
    });

    layout.vias.filter((via) => via.layers.includes(layer.id)).forEach((via) => {
        const code = addAperture("C", formatNumber(via.diameter));
        content.push(`D${code}*`, `${gerberPoint(via)}D03*`);
    });

    layout.footprints.forEach((footprint) => {
        const definition = getPartDefinition(footprint.type);
        footprint.pads.forEach((pad) => {
            if (pad.kind === "smd" && layer.side !== "top") return;
            const center = rotatePoint(pad.offset, footprint);
            if (pad.kind === "smd") {
                const halfWidth = options.smdPadWidthMm / 2;
                const halfHeight = options.smdPadHeightMm / 2;
                const corners = [
                    { x: -halfWidth, y: -halfHeight }, { x: halfWidth, y: -halfHeight },
                    { x: halfWidth, y: halfHeight }, { x: -halfWidth, y: halfHeight }
                ].map((point) => rotatePoint(point, { ...footprint, x: center.x, y: center.y }));
                const regionAperture = addAperture("C", "0.0100");
                content.push(`D${regionAperture}*`);
                content.push("G36*");
                content.push(`${gerberPoint(corners[0])}D02*`);
                corners.slice(1).forEach((point) => content.push(`${gerberPoint(point)}D01*`));
                content.push(`${gerberPoint(corners[0])}D01*`, "G37*");
            } else {
                const diameter = options.throughHolePadDiameterMm;
                const code = addAperture("C", formatNumber(diameter));
                content.push(`D${code}*`, `${gerberPoint(center)}D03*`);
            }
            if (!definition) throw new Error(`Missing component definition for ${footprint.reference}.`);
        });
    });
    content.push("M02*");
    return {
        content: content.join("\n"),
        hasUnfilledZones: layout.zones.some((zone) => zone.layerId === layer.id)
    };
}

function createGerberOutline(project) {
    const points = project.layout.outline;
    const content = createGerberHeader(`${project.name} · board profile`);
    const outlineWidth = 0.1;
    content.push(`%ADD10C,${formatNumber(outlineWidth)}*%`, "D10*");
    content.push(`${gerberPoint(points[0])}D02*`);
    points.slice(1).forEach((point) => content.push(`${gerberPoint(point)}D01*`));
    content.push(`${gerberPoint(points[0])}D01*`, "M02*");
    return content.join("\n");
}

function createDrillFile(project, options) {
    const holes = new Map();
    const addHole = (x, y, diameter) => {
        const key = `${formatNumber(x)}:${formatNumber(y)}:${formatNumber(diameter)}`;
        holes.set(key, { x, y, diameter });
    };
    project.layout.footprints.forEach((footprint) => {
        footprint.pads.filter((pad) => pad.kind !== "smd").forEach((pad) => {
            const point = rotatePoint(pad.offset, footprint);
            addHole(point.x, point.y, options.throughHoleDrillMm);
        });
    });
    project.layout.vias.forEach((via) => addHole(via.x, via.y, options.viaDrillMm));
    const tools = [...new Set([...holes.values()].map((hole) => formatNumber(hole.diameter)))].sort((a, b) => Number(a) - Number(b));
    const toolNumber = new Map(tools.map((diameter, index) => [diameter, index + 1]));
    const coordinate = (value) => {
        const scaled = Math.round(value * GERBER_SCALE);
        return `${scaled < 0 ? "-" : ""}${String(Math.abs(scaled)).padStart(7, "0")}`;
    };
    const drillName = String(project.name).replace(/[^\x20-\x7e]/g, " ").replace(/[\r\n;]/g, " ");
    const lines = ["M48", `; ${drillName} - Excellon drill data`, "METRIC,LZ,000.0000"];
    tools.forEach((diameter, index) => lines.push(`T${String(index + 1).padStart(2, "0")}C${diameter}`));
    lines.push("%");
    [...holes.values()].forEach((hole) => {
        const tool = toolNumber.get(formatNumber(hole.diameter));
        lines.push(`T${String(tool).padStart(2, "0")}`, `X${coordinate(hole.x)}Y${coordinate(hole.y)}`);
    });
    lines.push("M30");
    return lines.join("\n");
}

function createBom(project, getPartDefinition) {
    const items = new Map();
    project.layout.footprints.forEach((footprint) => {
        const definition = getPartDefinition(footprint.type) || {};
        const packageName = definition.footprint?.type || "Unspecified";
        const key = [footprint.value, footprint.type, packageName].join("\u0000");
        if (!items.has(key)) items.set(key, { value: footprint.value, type: footprint.type, packageName, references: [] });
        items.get(key).references.push(footprint.reference);
    });
    return csvRows([
        ["Value", "Component type", "Footprint", "Quantity", "References"],
        ...[...items.values()].map((item) => [
            item.value, item.type, item.packageName, item.references.length, item.references.sort().join(" ")
        ])
    ]);
}

function createPickAndPlace(project, getPartDefinition) {
    const placements = project.layout.footprints.flatMap((footprint) => {
        const definition = getPartDefinition(footprint.type);
        if (!definition?.footprint?.type?.toLowerCase().includes("smd")) return [];
        return [[footprint.reference, footprint.value, definition.footprint.type,
            formatNumber(footprint.x), formatNumber(footprint.y), formatNumber(footprint.rotation || 0), "Top"]];
    });
    return csvRows([
        ["Designator", "Value", "Package", "X (mm)", "Y (mm)", "Rotation (deg)", "Side"],
        ...placements.sort((a, b) => a[0].localeCompare(b[0]))
    ]);
}

function createNetlist(project) {
    const nets = project.layout.nets || [];
    return csvRows([
        ["Net", "Reference", "Pin"],
        ...nets.flatMap((net) => net.nodes.map((node) => [net.name, node.reference, node.pin]))
    ]);
}

