export function validatePcbManufacturingProject(project, options = {}, getPartDefinition = options.getPartDefinition) {
    const errors = [];
    const warnings = [];
    if (!project || !Number.isFinite(project.width) || !Number.isFinite(project.height) ||
        !Number.isFinite(project.thickness) || project.width <= 0 || project.height <= 0 ||
        project.thickness < 0.8 || project.thickness > 3.2) {
        errors.push("Board dimensions must be finite and positive; thickness must be between 0.8 and 3.2 mm.");
    }
    const outlineError = validateOutline(project?.layout?.outline);
    if (outlineError) errors.push(outlineError);
    if (!Array.isArray(project?.layout?.layers) || !Array.isArray(project?.layout?.footprints) ||
        !Array.isArray(project?.layout?.tracks) || !Array.isArray(project?.layout?.vias)) {
        errors.push("The PCB layout is missing manufacturing geometry.");
        return { errors, warnings };
    }
    const outline = project.layout.outline;
    const pointIsInside = (point) => outline?.length >= 3 && pointInPolygon(point, outline);
    if (outline?.length >= 3 && outline.every((point) => Number.isFinite(point.x) && Number.isFinite(point.y))) {
        const bounds = boundsOf(outline);
        if (bounds.minX < -0.01 || bounds.minY < -0.01 ||
            bounds.maxX > project.width + 0.01 || bounds.maxY > project.height + 0.01) {
            errors.push("Board outline extends beyond the configured board dimensions.");
        }
        if (Math.abs((bounds.maxX - bounds.minX) - project.width) > 0.1 ||
            Math.abs((bounds.maxY - bounds.minY) - project.height) > 0.1) {
            warnings.push("Board outline bounds do not match the nominal board width and height.");
        }
    }
    const references = new Set();
    project.layout.footprints.forEach((footprint) => {
        if (references.has(footprint.reference)) errors.push(`Duplicate footprint reference ${footprint.reference}.`);
        references.add(footprint.reference);
        if (!Number.isFinite(footprint.x) || !Number.isFinite(footprint.y) ||
            !Array.isArray(footprint.pads) || footprint.pads.some((pad) =>
                !Number.isFinite(pad.offset?.x) || !Number.isFinite(pad.offset?.y))) {
            errors.push(`Footprint ${footprint.reference} has invalid position or pad data.`);
            return;
        }
        if (outline?.length >= 3 && !pointInPolygon({ x: footprint.x, y: footprint.y }, outline)) {
            errors.push(`Footprint ${footprint.reference} is outside the board outline.`);
        }
        if (outline?.length >= 3 && footprint.pads.some((pad) =>
            !pointInPolygon(rotatePoint(pad.offset, footprint), outline))) {
            errors.push(`One or more pads on ${footprint.reference} are outside the board outline.`);
        }
    });
    project.layout.tracks.forEach((track) => {
        if (track.points.some((point) => !pointIsInside(point))) {
            errors.push(`Copper track ${track.id} has a vertex outside the board outline.`);
        }
    });
    project.layout.vias.forEach((via) => {
        if (!pointIsInside(via)) errors.push(`Via ${via.id} is outside the board outline.`);
        if (Number.isFinite(via.diameter) && options.viaDrillMm >= via.diameter) {
            errors.push(`Via drill for ${via.id} must be smaller than its modeled copper land diameter.`);
        }
    });
    if (Number.isFinite(options.throughHoleDrillMm) && Number.isFinite(options.throughHolePadDiameterMm) &&
        options.throughHoleDrillMm >= options.throughHolePadDiameterMm) {
        errors.push("Through-hole drill diameter must be smaller than its copper land diameter.");
    }
    for (const [label, value] of [
        ["Through-hole drill", options.throughHoleDrillMm],
        ["Via drill", options.viaDrillMm],
        ["Through-hole land", options.throughHolePadDiameterMm],
        ["SMD land width", options.smdPadWidthMm],
        ["SMD land height", options.smdPadHeightMm]
    ]) {
        if (value !== undefined && (!Number.isFinite(Number(value)) || Number(value) <= 0 || Number(value) > 10)) {
            errors.push(`${label} must be greater than 0 and no more than 10 mm.`);
        }
    }
    (options.selectedLayers || []).forEach((id) => {
        if (!project.layout.layers.some((layer) => layer.id === id &&
            (layer.type === "copper" || layer.type === "outline"))) {
            errors.push(`Selected export layer "${id}" is unavailable or unsupported.`);
        }
    });
    if (project.layout.zones.length) {
        warnings.push(`${project.layout.zones.length} copper zone(s) are omitted: zone filling and clearances are not implemented.`);
    }
    if (!project.layout.footprints.length) warnings.push("The board has no component footprints.");
    const footprintReferences = new Set(project.layout.footprints.map((footprint) => footprint.reference));
    const previewOnlyCount = (Array.isArray(project.components) ? project.components : []).filter((component) =>
        !footprintReferences.has(component.reference)).length;
    if (previewOnlyCount) {
        warnings.push(`${previewOnlyCount} 3D preview component(s) have no matching PCB layout footprint; BOM and fabrication geometry use only the placed layout footprints.`);
    }
    if (!project.layout.nets?.length) warnings.push("No synchronized PCB netlist is available; export the schematic netlist or sync the layout first.");
    if (options.outputs?.gerber) {
        warnings.push("Solder-mask and silkscreen Gerber layers are unsupported and are not included.");
    }
    if (options.outputs?.pickPlace &&
        !project.layout.footprints.some((footprint) => getFootprintKind(footprint, getPartDefinition) === "smd")) {
        warnings.push("No SMD placements are present; the pick-and-place CSV contains its header only.");
    }
    if (options.outputs && !Object.values(options.outputs).some(Boolean)) errors.push("Select at least one output file type.");
    if (options.outputs?.gerber && !options.selectedLayers?.some((id) =>
        project.layout.layers.some((layer) => layer.id === id && (layer.type === "copper" || layer.type === "outline")))) {
        errors.push("Select at least one supported copper or outline layer for Gerber output.");
    }
    return { errors, warnings: [...new Set(warnings)] };
}

function getFootprintKind(footprint, getPartDefinition) {
    return getPartDefinition?.(footprint.type)?.footprint?.type?.toLowerCase().includes("smd") ? "smd" : "through-hole";
}

export function generatePcbManufacturingFiles(project, configuration, getPartDefinition) {
    if (typeof getPartDefinition !== "function") throw new Error("A PCB component definition lookup is required.");
    const options = {
        selectedLayers: [...(configuration.selectedLayers || [])],
        outputs: { ...configuration.outputs },
        getPartDefinition,
        throughHoleDrillMm: Number(configuration.throughHoleDrillMm),
        viaDrillMm: Number(configuration.viaDrillMm),
        throughHolePadDiameterMm: Number(configuration.throughHolePadDiameterMm),
        smdPadWidthMm: Number(configuration.smdPadWidthMm),
        smdPadHeightMm: Number(configuration.smdPadHeightMm),
        generatedAt: configuration.generatedAt || new Date().toISOString()
    };
    for (const [label, value] of [
        ["Through-hole drill", options.throughHoleDrillMm],
        ["Via drill", options.viaDrillMm],
        ["Through-hole land", options.throughHolePadDiameterMm],
        ["SMD pad width", options.smdPadWidthMm],
        ["SMD pad height", options.smdPadHeightMm]
    ]) {
        if (!Number.isFinite(value) || value <= 0 || value > 10) throw new Error(`${label} must be between 0 and 10 mm.`);
    }
    const validation = validatePcbManufacturingProject(project, options, getPartDefinition);
    if (validation.errors.length) throw new Error(validation.errors.join(" "));

    const name = sanitizeFilePart(project.name);
    const files = [];
    const warnings = [...validation.warnings, ...(configuration.warnings || [])];
    if (options.outputs.gerber) {
        project.layout.layers.filter((layer) => options.selectedLayers.includes(layer.id)).forEach((layer) => {
            if (layer.type === "outline") {
                files.push({ path: `${name}.GKO`, format: "Gerber · board outline", content: createGerberOutline(project) });
            } else if (layer.type === "copper") {
                const result = createGerberCopper(project, layer, options, getPartDefinition);
                files.push({
                    path: `${name}.${layer.id === "top-copper" ? "GTL" : layer.id === "bottom-copper" ? "GBL" : `G${project.layout.layers.filter((entry) => entry.type === "copper" && entry.side === "inner").indexOf(layer) + 1}`}`,
                    format: `Gerber · ${layer.name}`,
                    content: result.content
                });
                if (result.hasUnfilledZones && !warnings.some((item) => item.includes("copper zone"))) {
                    warnings.push("Copper zone polygons are omitted; only tracks and pads are emitted.");
                }
            }
        });
    }
    if (options.outputs.drill) {
        files.push({ path: `${name}.DRL`, format: "Excellon drill", content: createDrillFile(project, options) });
    }
    if (options.outputs.bom) files.push({ path: `${name}-BOM.csv`, format: "Bill of materials · CSV", content: createBom(project, getPartDefinition) });
    if (options.outputs.pickPlace) files.push({
        path: `${name}-pick-and-place.csv`, format: "Pick-and-place · SMD CSV", content: createPickAndPlace(project, getPartDefinition)
    });
    if (options.outputs.netlist) files.push({ path: `${name}-netlist.csv`, format: "PCB netlist · Aqua CSV", content: createNetlist(project) });
    if (options.outputs.project) {
        files.push({ path: `${name}-project.json`, format: "Aqua PCB project · JSON", content: JSON.stringify(project, null, 2) });
    }
    if (options.outputs.documentation) {
        const bounds = boundsOf(project.layout.outline);
        const documentationOptions = {
            ...options,
            outlineBounds: { width: bounds.maxX - bounds.minX, height: bounds.maxY - bounds.minY }
        };
        files.push({
            path: `${name}-manufacturing.md`,
            format: "Manufacturing notes · Markdown",
            content: createManufacturingDocumentation(project, documentationOptions, warnings, [
                ...files, { path: `${name}-manufacturing.md` }
            ])
        });
    }
    if (!files.length) throw new Error("Select at least one export file type.");
    return { files, warnings };
}

const crcTable = Uint32Array.from({ length: 256 }, (_, value) => {
    let crc = value;
    for (let bit = 0; bit < 8; bit += 1) crc = crc & 1 ? 0xedb88320 ^ (crc >>> 1) : crc >>> 1;
    return crc >>> 0;
});

function crc32(bytes) {
    let crc = 0xffffffff;
    bytes.forEach((byte) => { crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8); });
    return (crc ^ 0xffffffff) >>> 0;
}

function write16(view, offset, value) { view.setUint16(offset, value, true); }
function write32(view, offset, value) { view.setUint32(offset, value, true); }

export function createPcbManufacturingZip(files, generatedAt = new Date()) {
    if (!Array.isArray(files) || !files.length) throw new Error("A project package needs at least one generated file.");
    if (files.length >= 0xffff) throw new Error("The project package contains too many files.");
    const encoder = new TextEncoder();
    const localParts = [];
    const centralParts = [];
    let offset = 0;
    const date = generatedAt instanceof Date ? generatedAt : new Date(generatedAt);
    const dosTime = (date.getHours() << 11) | (date.getMinutes() << 5) | Math.floor(date.getSeconds() / 2);
    const dosDate = ((Math.max(1980, date.getFullYear()) - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate();
    files.forEach((file) => {
        const path = encoder.encode(file.path);
        const body = encoder.encode(file.content);
        if (path.length > 0xffff || body.length > 0xffffffff || offset > 0xffffffff) {
            throw new Error("A package file exceeds the supported ZIP size.");
        }
        const checksum = crc32(body);
        const local = new Uint8Array(30 + path.length + body.length);
        const localView = new DataView(local.buffer);
        write32(localView, 0, 0x04034b50);
        write16(localView, 4, 20);
        write16(localView, 6, 0x0800);
        write16(localView, 8, 0);
        write16(localView, 10, dosTime);
        write16(localView, 12, dosDate);
        write32(localView, 14, checksum);
        write32(localView, 18, body.length);
        write32(localView, 22, body.length);
        write16(localView, 26, path.length);
        local.set(path, 30);
        local.set(body, 30 + path.length);
        localParts.push(local);

        const central = new Uint8Array(46 + path.length);
        const centralView = new DataView(central.buffer);
        write32(centralView, 0, 0x02014b50);
        write16(centralView, 4, 20);
        write16(centralView, 6, 20);
        write16(centralView, 8, 0x0800);
        write16(centralView, 10, 0);
        write16(centralView, 12, dosTime);
        write16(centralView, 14, dosDate);
        write32(centralView, 16, checksum);
        write32(centralView, 20, body.length);
        write32(centralView, 24, body.length);
        write16(centralView, 28, path.length);
        write32(centralView, 42, offset);
        central.set(path, 46);
        centralParts.push(central);
        offset += local.length;
    });
    const centralSize = centralParts.reduce((sum, part) => sum + part.length, 0);
    const end = new Uint8Array(22);
    const endView = new DataView(end.buffer);
    write32(endView, 0, 0x06054b50);
    write16(endView, 8, files.length);
    write16(endView, 10, files.length);
    write32(endView, 12, centralSize);
    write32(endView, 16, offset);
    const result = new Uint8Array(offset + centralSize + end.length);
    let cursor = 0;
    [...localParts, ...centralParts, end].forEach((part) => {
        result.set(part, cursor);
        cursor += part.length;
    });
    return result;
}
